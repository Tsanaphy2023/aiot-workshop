let activeQuizMode = 'pretest45';
let currentQuizQuestions = quizQuestionsMaster45;

function switchQuizMode(mode) {
  activeQuizMode = mode;
  const btn45 = document.getElementById('btn-quiz-mode-45') || document.getElementById('btn-quiz-mode-40');
  const btn10 = document.getElementById('btn-quiz-mode-10');
  const btnM4 = document.getElementById('btn-quiz-mode-m4');
  
  [btn45, btn10, btnM4].forEach(b => {
    if (b) {
      b.style.background = 'transparent';
      b.style.border = '1px solid rgba(255,255,255,0.2)';
      b.classList.remove('active');
    }
  });

  if (mode === 'pretest45' || mode === 'pretest40') {
    currentQuizQuestions = quizQuestionsMaster45;
    if (btn45) { btn45.style.background = ''; btn45.style.border = ''; btn45.classList.add('active'); }
  } else if (mode === 'module4') {
    currentQuizQuestions = quizQuestionsModule4;
    if (btnM4) { btnM4.style.background = ''; btnM4.style.border = ''; btnM4.classList.add('active'); }
  } else {
    currentQuizQuestions = quizQuestionsScenario;
    if (btn10) { btn10.style.background = ''; btn10.style.border = ''; btn10.classList.add('active'); }
  }
  const resultBox = document.getElementById('quiz-result-score');
  if (resultBox) resultBox.style.display = 'none';
  renderQuiz();
}

function renderQuiz() {
  const quizContainer = document.getElementById('quiz-questions-list');
  if (!quizContainer) return;

  quizContainer.innerHTML = '';
  currentQuizQuestions.forEach((item, index) => {
    const qDiv = document.createElement('div');
    qDiv.className = 'question-box';
    qDiv.id = `q-box-${index}`;

    let optionsHtml = '';
    item.options.forEach((opt, optIndex) => {
      optionsHtml += `
        <label class="choice-label" id="label-${index}-${optIndex}">
          <input type="radio" name="q_${index}" value="${optIndex}">
          <span>${opt}</span>
        </label>
      `;
    });

    qDiv.innerHTML = `
      <div class="question-title">${item.q}</div>
      <div class="choice-options">${optionsHtml}</div>
      <div class="quiz-feedback" id="feedback-${index}" style="display:none; margin-top:0.8rem; font-size:0.85rem; padding:0.6rem; border-radius:6px;"></div>
    `;

    quizContainer.appendChild(qDiv);
  });
}

function gradeQuiz() {
  let score = 0;
  let total = currentQuizQuestions.length;

  currentQuizQuestions.forEach((item, index) => {
    const selected = document.querySelector(`input[name="q_${index}"]:checked`);
    const feedback = document.getElementById(`feedback-${index}`);

    if (selected) {
      const val = parseInt(selected.value);
      if (val === item.ans) {
        score++;
        feedback.style.display = 'block';
        feedback.style.background = 'rgba(16, 185, 129, 0.15)';
        feedback.style.color = '#34d399';
        feedback.innerHTML = `✅ <b>ถูกต้อง!</b> ${item.explain}`;
      } else {
        feedback.style.display = 'block';
        feedback.style.background = 'rgba(239, 68, 68, 0.15)';
        feedback.style.color = '#f87171';
        feedback.innerHTML = `❌ <b>คำตอบที่ถูกต้องคือข้อ ${item.ans + 1}:</b> ${item.options[item.ans]}<br><small>${item.explain}</small>`;
      }
    } else {
      feedback.style.display = 'block';
      feedback.style.background = 'rgba(245, 158, 11, 0.15)';
      feedback.style.color = '#fbbf24';
      feedback.innerHTML = `⚠️ <i>ยังไม่ได้ตอบข้อนี้</i>`;
    }
  });

  const resultBox = document.getElementById('quiz-result-score');
  if (resultBox) {
    resultBox.style.display = 'block';
    const percent = Math.round((score / total) * 100);
    resultBox.innerHTML = `
      <h3>🎉 ผลการทดสอบ: ${score} / ${total} คะแนน (${percent}%)</h3>
      <p>${percent >= 80 ? '🌟 ยอดเยี่ยมมาก! ท่านมีความเข้าใจในระบบ AIoT และ Deep Learning เป็นอย่างดี' : '👍 ดีมาก! สามารถทบทวนบทเรียนและทำซ้ำได้ตามต้องการ'}</p>
    `;
    resultBox.scrollIntoView({ behavior: 'smooth' });

    // Send score to backend database
    const certName = document.getElementById('cert-name-input')?.value || 'ผู้เข้าอบรม';
    const certSchool = document.getElementById('cert-school-input')?.value || '-';
    fetch('/api/quiz', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        fullname: certName,
        school: certSchool,
        quiz_type: 'pretest',
        score: score,
        total: total
      })
    }).catch(e => console.log('Saved quiz offline'));
  }
}

